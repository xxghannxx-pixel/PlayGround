export function presetLook(name) {
  const preset = PRESETS[name] || PRESETS.natural;
  return normalizeLook({ ...emptyLook(), ...preset.overrides });
}

const ID_SETS = {
  skin: SKINS,
  hairColor: HAIRS,
  eyeColor: EYES,
  blushColor: BLUSHES,
  shadowColor: SHADOWS,
  lips: LIPS,
  linerColor: LINERS,
  browColor: BROWS,
  aura: AURAS
};
const ENUMS = {
  hairstyle: ['loose', 'updo', 'bob'],
  shadowFinish: ['matte', 'satin', 'glitter'],
  liner: ['none', 'soft', 'wing', 'bold'],
  lashes: ['none', 'natural', 'glam'],
  brows: ['natural', 'arched', 'straight'],
  lipFinish: ['matte', 'satin', 'gloss'],
  earrings: ['none', 'hoops', 'pearl', 'drop'],
  necklace: ['none', 'chain', 'pearls']
};
const BOOLS = ['freckles', 'mole', 'lipLiner', 'glitter'];
const NUMS = {
  blushIntensity: [0, 1], contour: [0, 1], highlight: [0, 1],
  shadowIntensity: [0, 1], lipIntensity: [0, 1]
};

export function normalizeLook(raw) {
  const base = emptyLook();
  if (!raw || typeof raw !== 'object') return base;
  const out = { ...base };
  for (const [key, list] of Object.entries(ID_SETS)) {
    if (typeof raw[key] === 'string' && list.some(item => item.id === raw[key])) out[key] = raw[key];
  }
  for (const [key, list] of Object.entries(ENUMS)) {
    if (list.includes(raw[key])) out[key] = raw[key];
  }
  for (const key of BOOLS) if (typeof raw[key] === 'boolean') out[key] = raw[key];
  for (const [key, [min, max]] of Object.entries(NUMS)) {
    if (Number.isFinite(raw[key])) out[key] = Math.min(max, Math.max(min, raw[key]));
  }
  if (Array.isArray(raw.stickers)) {
    out.stickers = raw.stickers
      .filter(s => s && ['gem', 'star', 'heart', 'flower', 'pearl'].includes(s.type)
        && Number.isFinite(s.x) && Number.isFinite(s.y))
      .slice(0, 80)
      .map(s => ({
        type: s.type,
        x: s.x, y: s.y,
        scale: Number.isFinite(s.scale) ? Math.min(2.2, Math.max(.4, s.scale)) : 1,
        rot: Number.isFinite(s.rot) ? s.rot : 0
      }));
  }
  if (Array.isArray(raw.strokes)) {
    out.strokes = raw.strokes
      .filter(s => s && Array.isArray(s.points) && s.points.length)
      .slice(0, 220)
      .map(s => ({
        color: typeof s.color === 'string' ? s.color : '#c96f8c',
        size: Number.isFinite(s.size) ? Math.min(48, Math.max(1, s.size)) : 8,
        opacity: Number.isFinite(s.opacity) ? Math.min(1, Math.max(.05, s.opacity)) : .8,
        mode: ['draw', 'glitter', 'erase'].includes(s.mode) ? s.mode : 'draw',
        points: s.points
          .filter(p => p && Number.isFinite(p.x) && Number.isFinite(p.y))
          .slice(0, 900)
          .map(p => ({ x: p.x, y: p.y }))
      }))
      .filter(s => s.points.length);
  }
  return out;
}

